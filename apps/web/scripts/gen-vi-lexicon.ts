#!/usr/bin/env tsx
/**
 * Writes `worker/vi-lexicon.ts`: every marked syllable that a Viet74K entry
 * uses (github.com/duyet/vietnamese-wordlist). Typos in the list fail
 * `isVietnameseSpelling` and are left out.
 *
 * Usage (from apps/web):
 *   curl -sLO https://raw.githubusercontent.com/duyet/vietnamese-wordlist/master/Viet74K.txt
 *   pnpm exec tsx scripts/gen-vi-lexicon.ts Viet74K.txt
 */
import { readFileSync, writeFileSync } from "node:fs";
import { isVietnameseSpelling } from "../worker/vi-syllable";

const input = process.argv[2];
if (!input) throw new Error("usage: gen-vi-lexicon.ts <Viet74K.txt>");

const syllables = new Set<string>();
for (const word of readFileSync(input, "utf8")
  .normalize("NFC")
  .toLowerCase()
  .split(/\s+/)) {
  if (/^\p{L}+$/u.test(word) && !/^\p{ASCII}+$/u.test(word)) {
    if (isVietnameseSpelling(word)) syllables.add(word);
  }
}

const sorted = [...syllables].sort();
writeFileSync(
  new URL("../worker/vi-lexicon.ts", import.meta.url),
  `/** Generated by scripts/gen-vi-lexicon.ts from Viet74K. Do not edit. */\nexport const VI_MARKED_SYLLABLES: ReadonlySet<string> = new Set(\n  "${sorted.join(" ")}".split(" ")\n);\n`
);
console.log(`${sorted.length} syllables`);
